const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('kivo', {
  min: () => ipcRenderer.send('win:min'),
  max: () => ipcRenderer.send('win:max'),
  close: () => ipcRenderer.send('win:close'),
  onWinState: (fn) => ipcRenderer.on('win:state', (_e, v) => fn(v)),
  load: () => ipcRenderer.invoke('data:load'),
  save: (d) => ipcRenderer.invoke('data:save', d),
  keyStatus: () => ipcRenderer.invoke('keys:status'),
  setKeys: (p) => ipcRenderer.invoke('keys:set', p),
  ask: (o) => ipcRenderer.invoke('claude:ask', o),
  printify: (o) => ipcRenderer.invoke('printify:req', o),
  saveFile: (o) => ipcRenderer.invoke('file:save', o),
  saveDir: (o) => ipcRenderer.invoke('file:saveDir', o),
  onUpdate: (fn) => ipcRenderer.on('update:state', (_e, v) => fn(v)),
  installUpdate: () => ipcRenderer.send('update:install'),
  version: () => ipcRenderer.invoke('app:version'),
  getPrefs: () => ipcRenderer.invoke('prefs:get'),
  setPrefs: (p) => ipcRenderer.invoke('prefs:set', p),
  trayState: (st) => ipcRenderer.send('tray:state', st),
  onTray: (fn) => ipcRenderer.on('tray:cmd', (_e, c) => fn(c)),
  notify: (title, body) => ipcRenderer.send('notify', { title, body }),
  onDelta: (fn) => ipcRenderer.on('claude:delta', (_e, v) => fn(v)),
  cancelAll: () => ipcRenderer.send('claude:cancelAll'),
  cancelReq: (ids) => ipcRenderer.send('claude:cancel', ids),
  mediaSave: (o) => ipcRenderer.invoke('media:save', o),
  mediaRead: (f) => ipcRenderer.invoke('media:read', f),
  mediaSize: (f) => ipcRenderer.invoke('media:size', f),
  fetchImage: (u) => ipcRenderer.invoke('net:image', u),
  videoSlides: (o) => ipcRenderer.invoke('video:slides', o),
  videoPick: () => ipcRenderer.invoke('video:pick'),
  videoFrames: (o) => ipcRenderer.invoke('video:frames', o),
  videoEdit: (o) => ipcRenderer.invoke('video:edit', o),
  pathOf: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  socialGet: () => ipcRenderer.invoke('social:get'),
  socialSet: (p) => ipcRenderer.invoke('social:set', p),
  socialReq: (o) => ipcRenderer.invoke('social:req', o),
  socialHost: (o) => ipcRenderer.invoke('social:host', o),
  oauthStart: (o) => ipcRenderer.invoke('oauth:start', o),
  oauthPkce: () => ipcRenderer.invoke('oauth:pkce'),
  openUrl: (u) => ipcRenderer.send('open:url', u),
  openFile: (o) => ipcRenderer.invoke('file:open', o),
  tgSet: (o) => ipcRenderer.invoke('tg:set', o), tgStatus: () => ipcRenderer.invoke('tg:status'), tgSend: (o) => ipcRenderer.invoke('tg:send', o),
  onTg: (fn) => { ipcRenderer.on('tg:msg', (_e, v) => fn('msg', v)); ipcRenderer.on('tg:cb', (_e, v) => fn('cb', v)); ipcRenderer.on('tg:paired', (_e, v) => fn('paired', v)); ipcRenderer.on('tg:error', (_e, v) => fn('error', v)); },
  mailSet: (p) => ipcRenderer.invoke('mail:set', p), mailStatus: () => ipcRenderer.invoke('mail:status'), mailTest: () => ipcRenderer.invoke('mail:test'), mailSend: (o) => ipcRenderer.invoke('mail:send', o),
  hookPost: (o) => ipcRenderer.invoke('hook:post', o),
  folderPick: (o) => ipcRenderer.invoke('folder:pick', o), folderWrite: (o) => ipcRenderer.invoke('folder:write', o),
  backupTo: (o) => ipcRenderer.invoke('backup:to', o), backupSave: () => ipcRenderer.invoke('backup:save'), backupRestore: () => ipcRenderer.invoke('backup:restore'),
  licGet: () => ipcRenderer.invoke('lic:get'), licSet: (k) => ipcRenderer.invoke('lic:set', k),
  stt: (o) => ipcRenderer.invoke('stt', o),
});
